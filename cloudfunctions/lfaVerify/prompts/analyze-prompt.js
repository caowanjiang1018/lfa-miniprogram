/**
 * 任务 D 的用户消息
 * @param {object} topic 课题
 * @param {Array} cands 已检索到的候选记录（由系统从真实返回里裁剪出来）
 */
function buildUser(topic, cands) {
  topic = topic || {};
  var lines = ['课题如下：'];
  if (topic.name) lines.push('课题名称：' + topic.name);
  if (topic.problem) lines.push('研究问题：' + topic.problem);
  if (topic.target) lines.push('对象或场景：' + topic.target);
  if (topic.task) lines.push('期望完成的任务：' + topic.task);
  if (topic.claim) lines.push('拟让文献支持的说法：' + topic.claim);

  lines.push('');
  lines.push('下面是本次真实检索到的候选记录（编号 = id）：');
  for (var i = 0; i < cands.length; i++) {
    var c = cands[i] || {};
    lines.push('---');
    lines.push('id：' + c.id);
    lines.push('题名：' + (c.title || '（该来源未提供题名）'));
    lines.push('作者：' + (c.authors || '（该来源未提供作者）'));
    lines.push('年份：' + (c.year || '（该来源未提供年份）'));
    lines.push('出处：' + (c.venue || '（该来源未提供出处）'));
    lines.push('类型：' + (c.type || '（未知）'));
    lines.push('DOI：' + (c.doi || '（无 DOI）'));
    /* 摘要【只】在检索接口真的返回了时才出现；否则明确写没有，堵住模型补写摘要的路 */
    lines.push('摘要：' + (c.abstract ? c.abstract : '（该来源未提供摘要，只能依据题录判断，禁止补写摘要）'));
  }
  lines.push('---');
  lines.push('请只依据上面给出的材料分析，不要新增任何文献，不要输出百分比评分，不要写链接。');
  return lines.join('\n');
}

/** 任务 D 输出字段的 JSON Schema 示意（仅用于文档与自检，不参与调用） */
var OUTPUT_SCHEMA = {
  items: [{
    id: 'string', match: ['string'], gap: ['string'],
    uses: ['了解背景|借鉴方法|寻找直接相关研究'], todo: ['string'], why: 'string'
  }],
  note: 'string'
};

module.exports = {
  SYSTEM: SYSTEM,
  buildUser: buildUser,
  OUTPUT_SCHEMA: OUTPUT_SCHEMA
};
